#!/usr/bin/env node
// credits-build.mjs — dependency-free. Reads every credit file under site/ and skills/ (<asset>.credit.json and folder credit.json)
// and writes CREDITS_generated.md grouped by home / Lab demo / library concept / shared kit / skill, one row per source
// (files sharing the same source + licence are folded into one row with their file list).
// Usage: node tools/credits-build.mjs [--out CREDITS_generated.md]
import fs from 'node:fs'; import path from 'node:path';
const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const args = process.argv.slice(2); const oi = args.indexOf('--out'); const OUT = path.resolve(ROOT, oi >= 0 ? args[oi + 1] : 'CREDITS_generated.md');
const creds = [];
(function walk(d) { if (!fs.existsSync(d)) return; for (const e of fs.readdirSync(d, { withFileTypes: true })) {
  if (e.name.startsWith('.') || e.name === 'node_modules' || e.name === 'vendor' || e.name === '_template' || e.name === '_test') continue;
  const p = path.join(d, e.name); if (e.isDirectory()) walk(p); else if (e.name.endsWith('.credit.json') || e.name === 'credit.json') creds.push(p); } })(path.join(ROOT, 'site'));
(function walk(d) { if (!fs.existsSync(d)) return; for (const e of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, e.name);
  if (e.isDirectory() && e.name !== 'node_modules') walk(p); else if (e.name.endsWith('.credit.json') || e.name === 'credit.json') creds.push(p); } })(path.join(ROOT, 'skills'));
function group(rel) {
  let m;
  if ((m = rel.match(/^site\/(?:assets\/)?lab\/([\w-]+)\//))) return ['Lab demos', m[1]];
  if ((m = rel.match(/^site\/library\/(n|a|p)\/(\w+)\//))) return ['Library concepts', m[2]];
  if (rel.startsWith('site/library/_assets/') || rel.startsWith('site/library/_kit/')) return ['Library shared kit', '_assets / _kit'];
  if ((m = rel.match(/^skills\/([\w-]+)\//))) return ['Skills', m[1]];
  if (rel.startsWith('site/assets/font/') || rel.startsWith('site/assets/hdri/')) return ['Shared site assets', 'fonts and HDRI'];
  if ((m = rel.match(/^site\/(color|process|services|studio\/\w+)\//))) return ['Studio pages', m[1]];
  if (rel.startsWith('site/assets/studio/')) return ['Studio pages', 'studio/' + rel.split('/')[3]];
  return ['Home page', 'home (index.html, m/index.html, worlds)'];
}
const tree = {}; let n = 0;
for (const p of creds.sort()) {
  let c; try { c = JSON.parse(fs.readFileSync(p, 'utf8')); } catch { continue; }
  const rel = path.relative(ROOT, p).split(path.sep).join('/');
  const files = p.endsWith('/credit.json') ? [(c.files ? c.files.length + ' files in ' : 'all files in ') + path.dirname(rel) + '/'] : [rel.replace(/\.credit\.json$/, '')];
  const [g, s] = group(rel); const key = [c.source_url, c.licence, c.title].join('|');
  tree[g] ??= {}; tree[g][s] ??= {}; const row = (tree[g][s][key] ??= { c, files: [] }); row.files.push(...files); n++;
}
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const order = ['Home page', 'Shared site assets', 'Lab demos', 'Studio pages', 'Library concepts', 'Library shared kit', 'Skills'];
let md = `# Credits (generated)\n\nGenerated by \`node tools/credits-build.mjs\` from ${n} credit files on ${new Date().toISOString().slice(0, 10)}. One row per source; every asset file has its own credit file next to it (\`<file>.credit.json\`, or one \`credit.json\` for a folder that holds one asset such as a frame sequence). \`node tools/credits-check.mjs\` is the gate. The hand-written CREDITS.md keeps the build notes.\n\nCode and design: Zyqor Studio (MIT). Personal content (Zyqor name and logo, Sujon's photo, intro and case-study clips) is all rights reserved, see LICENSE.md.\n`;
for (const g of order.filter((g) => tree[g])) {
  md += `\n## ${g}\n`;
  for (const s of Object.keys(tree[g]).sort()) {
    md += `\n### ${s}\n\n| Asset | Author | Source | Licence | Required credit | Changes | Downloaded | Files |\n|---|---|---|---|---|---|---|---|\n`;
    for (const { c, files } of Object.values(tree[g][s])) {
      const fl = files.length > 4 ? files.slice(0, 3).map((f) => '`' + f + '`').join(', ') + ` +${files.length - 3} more` : files.map((f) => '`' + f + '`').join(', ');
      const lic = c.licence_url ? `[${esc(c.licence)}](${c.licence_url})` : esc(c.licence);
      const flag = c.licence_flag ? ' **REVIEW:** ' + esc(c.licence_flag) : (c.verified === false ? ' **UNVERIFIED author**' : '');
      md += `| ${esc(c.title)} | ${c.author_url ? `[${esc(c.author)}](${c.author_url})` : esc(c.author)} | ${c.source_url ? `[link](${c.source_url})` : ''} | ${lic}${flag} | ${esc(c.attribution)} | ${esc(c.changes)} | ${esc(c.downloaded)} | ${fl} |\n`;
    }
  }
}
fs.writeFileSync(OUT, md); console.log(JSON.stringify({ out: path.relative(ROOT, OUT), credit_files: n, groups: Object.fromEntries(Object.entries(tree).map(([g, v]) => [g, Object.keys(v).length])) }));
