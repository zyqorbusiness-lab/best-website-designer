export function fontFaces(fonts, known) {
  const out = []; const fam = {};
  for (const role of ['display', 'body']) {
    const f = fonts[role];
    if (!f || f === 'system') { fam[role] = role === 'display' ? '"Arial Narrow","Helvetica Neue",Arial,sans-serif' : 'system-ui,-apple-system,"Segoe UI",Roboto,sans-serif'; continue; }
    const k = known[f]; if (!k) throw new Error(`font "${f}" is not a known file in site/assets/font/`);
    if (!out.some((o) => o.includes(f + '.woff2'))) out.push(`@font-face{font-family:"${k.family}";src:url("../../assets/font/${f}.woff2") format("woff2");font-weight:${k.weight};font-style:${k.style || 'normal'};font-display:swap}`);
    fam[role] = `"${k.family}",${role === 'display' ? 'Impact,"Arial Narrow",sans-serif' : 'system-ui,sans-serif'}`;
  }
  return { css: out.join('\n'), display: fam.display, body: fam.body, displayWeight: fonts.displayWeight || (known[fonts.display] && known[fonts.display].useWeight) || 800 };
}

